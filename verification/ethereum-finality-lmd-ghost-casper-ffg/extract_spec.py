def blocks(path):
    text = open(path, encoding="utf-8").read()
    return re.findall(r"^```python\n(.*?)^```", text, re.S | re.M)


def define(block, name):
    return re.search(rf"^(?:def {name}\(|class {name}\b)", block, re.M) is not None


def extract(root):
    found, out = {}, []
    for fork in FORKS:
        for doc in DOCS:
            path = os.path.join(root, "specs", fork, doc)
            if not os.path.exists(path):
                continue
            for block in blocks(path):
                for name in NAMES:
                    if define(block, name):
                        found[name] = (f"specs/{fork}/{doc}", block)
    missing = [n for n in NAMES if n not in found]
    if missing:
        raise SystemExit(f"not found: {missing}")
    head = subprocess.run(["git", "-C", root, "rev-parse", "HEAD"], capture_output=True,
                          text=True, check=True).stdout.strip()
    out.append(f'"""Generated by extract_spec.py from ethereum/consensus-specs at {head}.\n\n'
               "Every definition below is verbatim. Do not edit.\n\"\"\"\n")
    for name in NAMES:
        path, block = found[name]
        out.append(f"# --- {name}: {path}\n{block}\n")
    return head, "".join(out), found


def main():
    root = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    target = os.path.join(here, "spec_functions.py")
    head, text, found = extract(root)
    if head != PIN:
        print(f"note: checkout is {head}, the article pins {PIN}")
    if "--check" in sys.argv:
        same = open(target, encoding="utf-8").read() == text
        print("spec_functions.py matches a fresh extraction:", same)
        print("sha256:", hashlib.sha256(text.encode()).hexdigest())
        sys.exit(0 if same else 1)
    open(target, "w", encoding="utf-8").write(text)
    print(f"wrote {len(found)} definitions, sha256 {hashlib.sha256(text.encode()).hexdigest()}")
    by_source = {}
    for name, (path, _) in found.items():
        by_source.setdefault(path, []).append(name)
    for path in sorted(by_source):
        print(f"  {path}: {len(by_source[path])}")


main()

"""Write the Foundry fixtures from the pinned mainnet block."""
import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import beacon_types as B  # noqa: E402
import eip6404  # noqa: E402
import rlp_codec as R  # noqa: E402
from keccak import keccak256  # noqa: E402
from mainnet import load, rlp_withdrawal  # noqa: E402
from rlp_codec import to_int  # noqa: E402
from ssz_codec import List  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
FX = ROOT / "fixtures"
FX.mkdir(exist_ok=True)
raw, sb, el, rc, hdr = load()
pl = sb["message"]["body"]["execution_payload"]
wds = pl["withdrawals"]
txs = pl["transactions"]


def put(n, b):
    (FX / f"{n}.hex").write_text("0x" + b.hex())


w = wds[0]
wr, ws = R.encode(rlp_withdrawal(w)), B.Withdrawal.ser(w)
put("withdrawal_rlp", wr)
put("withdrawal_ssz", ws)
put("withdrawals_rlp", R.encode([rlp_withdrawal(x) for x in wds]))
put("withdrawals_ssz", List(B.Withdrawal, 16).ser(wds))

# EIP-1559 calls with a `to`: the median-sized one, and the largest.
t2 = sorted((t for t in txs if t[0] == 2 and R.decode(t[1:])[5]), key=len)
small, big = t2[len(t2) // 2], t2[-1]
ss = eip6404.Transaction.ser(eip6404.convert(small))
bs = eip6404.Transaction.ser(eip6404.convert(big))
put("tx_rlp", small)
put("tx_ssz", ss)
put("bigtx_rlp", big)
put("bigtx_ssz", bs)
first = txs[:32]
put("txs_rlp", R.encode([t if t[0] < 0xC0 else t for t in first]))
put("txs_ssz", List(B.Transaction, 2**20).ser(first))
print("median type-2", len(small), len(ss), "largest type-2", len(big), len(bs))

addr = keccak256(w["address"].hex().encode())
cs = "0x" + "".join(c.upper() if addr[i // 2] >> (4 if i % 2 == 0 else 0) & 8 else c
                    for i, c in enumerate(w["address"].hex()))
(ROOT / "test/Expected.sol").write_text(f"""// SPDX-License-Identifier: MIT
// Generated by python/gen_fixtures.py from the pinned mainnet block.
pragma solidity 0.8.30;

library Expected {{
    uint256 internal constant W0_INDEX = {w['index']};
    uint256 internal constant W0_VALIDATOR = {w['validator_index']};
    address internal constant W0_ADDRESS = {cs};
    uint256 internal constant W0_AMOUNT = {w['amount']};
    bytes32 internal constant W0_KECCAK = 0x{keccak256(wr).hex()};
    bytes32 internal constant W0_SHA256 = 0x{hashlib.sha256(ws).hexdigest()};
    bytes32 internal constant W0_ROOT = 0x{B.Withdrawal.htr(w).hex()};
    uint256 internal constant SUM_AMOUNTS = {sum(x['amount'] for x in wds)};
    uint256 internal constant TX_VALUE = {to_int(R.decode(small[1:])[6])};
    uint256 internal constant BIGTX_VALUE = {to_int(R.decode(big[1:])[6])};
}}
""")
